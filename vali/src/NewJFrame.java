    private void Namevalid(){
    String name = txtName.getText().trim();

    if(name.isEmpty()){
        display1.setText("Field is empty");
        display1.setForeground(Color.red);
    }
    else if(name.matches("[a-zA-Z ]+") && name.length() >= 3 && name.length() <= 30){
        display1.setText("Valid");
        display1.setForeground(Color.green);
    }
    else{
        display1.setText("Enter a valid name");
        display1.setForeground(Color.red);
    }
    }
    private void IDvalid(){
        String Student_ID_Number = txtID.getText();
        
      if(!Student_ID_Number.matches("\\d+")){
    display3.setText("Enter numbers only");
    display3.setForeground(Color.red);
}
else if (Student_ID_Number.length() != 13){
    display3.setText("Enter 13 digit ID number");
    display3.setForeground(Color.red);
}
else {
    display3.setText("Valid");
    display3.setForeground(Color.green);
}
    }
    private void PhoneNumber(){
        String Phone_Number = txtnumber.getText();
        
        if(Phone_Number.isEmpty()){
            display2.setText("Field is empty");
            display2.setForeground(Color.red);
        }
        else if(!Phone_Number.matches("\\d+")){
        display2.setText("Enter number");
        display2.setForeground(Color.red);
    }
        else if(Phone_Number.length() != 10){
            display2.setText("Enter the 10 digits");
            display2.setForeground(Color.red);
        }
        else{
            display2.setText("Valid");
            display2.setForeground(Color.green);
        }
    }
