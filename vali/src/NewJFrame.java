        private void Emailvalid(){
           String Email = txtEmail.getText();
           
           if(Email.isEmpty()){
               display4.setText("Field is empty");
               display4.setForeground(Color.red);
           }
           else if(Email.matches("^[A-Za-z0-9+_.-]+@gmail\\.com$")){
               display4.setText("Valid");
               display4.setForeground(Color.green);
        
        }
           else{
               display4.setText("Invalid");
               display4.setForeground(Color.red);
           }
        
        }
        private void DOBvalid(){
    String dob = txtDOB.getText().trim();

    if(dob.isEmpty()){
        display5.setText("Field is empty");
        display5.setForeground(Color.red);
    }
    else if(dob.matches("\\d{2}/\\d{2}/\\d{4}")){
        display5.setText("Valid");
        display5.setForeground(Color.green);
    }
    else{
        display5.setText("Use DD/MM/YYYY");
        display5.setForeground(Color.red);
    }
}   
